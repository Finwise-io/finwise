/** THE FIGURE REGISTER, WRITTEN OUT — founder rule 11, step 3 (2026-09-14).
 *
 *  The declarations live in TypeScript, beside the code that computes each figure. The master file is
 *  built in Python. This writes the register to
 *  Calculation Module code/scripts/moneykeel_figures.json so the builder can PRINT the figure rows
 *  from the declarations instead of the hand-typed lists that were the origin of every mismatch.
 *
 *  It is a test rather than a script so it runs in the suite and cannot rot: a declaration that no
 *  longer type-checks, or two doors claiming one identifier, fails here.
 */
import * as fs from 'fs';
import { FIGURE_REGISTER, FIGURE_DOOR } from '../../MoneyKeel/functions/figures';

const OUT = 'Calculation Module code/scripts/moneykeel_figures.json';

test('every declared figure is complete, and the register is written for the build', () => {
  const bad: string[] = [];
  for (const [id, f] of Object.entries(FIGURE_REGISTER)) {
    if (!/^MK-[A-Z]{2}-M-\d{3}$/.test(id)) bad.push(`${id}: not a metric identifier`);
    for (const k of ['label', 'unit', 'answers', 'formula', 'refusal'] as const) if (!f[k]) bad.push(`${id}: ${k} is blank`);
    if (!f.screens?.length) bad.push(`${id}: names no screen`);
    if (!f.inputs?.length) bad.push(`${id}: names no input`);
    if (f.formula.length < 20) bad.push(`${id}: the formula is not a formula a person could follow`);
  }
  expect(bad).toEqual([]);

  const out = Object.fromEntries(Object.entries(FIGURE_REGISTER).map(([id, f]) => [id, { ...f, door: FIGURE_DOOR[id] }]));
  fs.writeFileSync(OUT, JSON.stringify({ _about: 'GENERATED by src/__tests__/figure_register_export.test.ts from the doors\' own declarations (founder rule 11). Hand edits die: the declaration in the code is the only copy.', generated: new Date().toISOString().slice(0, 10), figures: out }, null, 1));
  expect(Object.keys(out).length).toBeGreaterThan(0);
});
